def language(text,previous='ru'):
    if re.search('[әғқңөұүһі]',text.lower()) or re.search(r'\b(сәлем|рахмет|иә|жоқ|калай|кайда|аудару)\b',text.lower()):return 'kk'
    if re.search(r'\b(да|нет|где|как|привет|покажи|дальше|назад|спасибо)\b',text.lower()):return 'ru'
    return previous if previous in {'ru','kk'} else 'ru'

def view(state):
    key=state.tutorial_active
    if not key:return None
    lang=state.language; k=1 if lang=='kk' else 0; g=GUIDES[key]
    return {'id':key,'title':g[lang],'index':state.tutorial_step,'source':SOURCE if key=='transfer' else None,
      'steps':[{'title':s[k],'text':s[2+k],'target':s[4+k]} for s in g['steps']]}

def handle(text,state):
    low=text.lower().strip(' .!?');state.language=language(text,state.language);kk=state.language=='kk'
    yes=bool(re.fullmatch(r'(да|давай|покажи|покажите|да покажи|да помоги|хорошо|иә|ия|көрсет|жарайды|yes)',low))
    no=low in {'нет','не надо','жоқ','no','закрыть','стоп','тоқта'}
    if state.tutorial_active:
        if no:
            state.tutorial_active=None
            return 'Нұсқаулық жабылды.' if kk else 'Закрыла подсказки. Чем ещё помочь?'
        if low in {'дальше','далее','следующий','келесі','назад','артқа'}:
            delta=-1 if low in {'назад','артқа'} else 1
            state.tutorial_step=max(0,min(len(GUIDES[state.tutorial_active]['steps'])-1,state.tutorial_step+delta))
            return view(state)['steps'][state.tutorial_step]['text']
    if state.tutorial_pending and (yes or no):
        key=state.tutorial_pending;state.tutorial_pending=None
        if no:return 'Жақсы. Басқа сұрағыңыз бар ма?' if kk else 'Хорошо. Если понадобится, я рядом.'
        state.tutorial_active=key;state.tutorial_step=0
        return view(state)['steps'][0]['text']
    help_intent=re.search(r'где|куда|как (найти|открыть|сделать|перевести)|не (могу|наш[её]л|понимаю)|нажать|покажи|қайда|қалай|таба алма|көрсет',low)
    if help_intent:
        key='transfer' if re.search(r'перев|аудар|получател',low) else 'navigation'
        state.tutorial_pending=key;state.tutorial_active=None
        return ('Қай жерді басу керегін қадамдап көрсетейін бе?' if kk else 'Давайте помогу разобраться. Показать на экране, куда нажимать, шаг за шагом?')
    if low in {'привет','здравствуйте','сәлем','сәлеметсіз бе'}:
        return 'Сәлем! Мен сіздің AI көмекшіңізбін. Қандай сұрағыңыз бар?' if kk else 'Здравствуйте! Я ваш AI-помощник. Расскажите, с чем помочь?'
    if low in {'спасибо','рахмет'}:return 'Көмектесуге дайынмын!' if kk else 'Рада помочь! Обращайтесь, если появятся вопросы.'
    state.tutorial_pending=None
    return None
